"""Clearly-labelled TEST carrier invoices for verifying Zoree's invoice PDF intake against real shipments."""
import sys
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors

def m(x): return f"${x:,.2f}"

def kllm(c, num, shp, dt, pro, lines, total, o, d, sd):
    W, H = letter
    c.setFont("Helvetica-Bold", 18); c.setFillColor(colors.HexColor("#8b1a1a")); c.drawString(40, H-55, "KLLM Transport Services — TEST INVOICE")
    c.setFillColor(colors.black); c.setFont("Helvetica", 9)
    c.drawString(40, H-70, "Test document generated by Zoree AI to verify invoice PDF intake. Not a real bill.")
    c.setStrokeColor(colors.HexColor("#8b1a1a")); c.setLineWidth(2); c.line(40, H-80, W-40, H-80); c.setLineWidth(1)
    c.setFont("Helvetica-Bold", 11); c.drawString(40, H-110, f"INVOICE # {num}")
    c.setFont("Helvetica", 10)
    c.drawString(40, H-128, f"Date issued: {dt}"); c.drawString(40, H-142, f"Load / BOL: {pro}"); c.drawString(40, H-156, f"Your reference: {shp}")
    c.drawString(330, H-110, "Customer:")
    for i, l in enumerate(["Zoree LLC (TEST)", "Accounts Payable", "Sheridan, WY"]): c.drawString(330, H-124-i*13, l)
    c.setStrokeColor(colors.grey); c.rect(40, H-235, W-80, 50, stroke=1, fill=0)
    c.drawString(50, H-205, f"Pick up: {o}  ({sd})"); c.drawString(50, H-222, f"Deliver: {d}")
    c.drawString(330, H-205, "Equipment: 53' dry van"); c.drawString(330, H-222, "Mode: FTL")
    y = H-275
    c.setFont("Helvetica-Bold", 10); c.drawString(50, y, "Charge"); c.drawRightString(W-50, y, "Total"); y -= 6
    c.line(40, y, W-40, y); y -= 16; c.setFont("Helvetica", 10)
    for desc, amt in lines: c.drawString(50, y, desc); c.drawRightString(W-50, y, m(amt)); y -= 18
    c.line(40, y+8, W-40, y+8)
    c.setFont("Helvetica-Bold", 11); c.drawString(300, y-10, "Amount due (USD)"); c.drawRightString(W-50, y-10, m(total))
    c.setFont("Helvetica-Oblique", 8); c.drawString(40, 60, "TEST ONLY — generated to exercise Zoree AI invoice intake.")

OUT = sys.argv[1]
for f, num, shp, pro, lines, total, sd in [
  ("TEST-KLLM-0001.pdf", "TEST-KLLM-0001", "SHP-2026-992029", "KLLM-TEST-1", [("Truckload linehaul", 1814.00), ("Fuel surcharge", 417.00)], 2231.00, "2026-11-03"),
  ("TEST-KLLM-0002.pdf", "TEST-KLLM-0002", "SHP-2026-894867", "KLLM-TEST-2", [("Truckload linehaul", 1814.00), ("Fuel surcharge", 417.00), ("Liftgate - delivery", 85.00)], 2316.00, "2026-11-04"),
]:
    c = canvas.Canvas(f"{OUT}/{f}", pagesize=letter); c.setTitle(f"Invoice {num} (TEST)")
    kllm(c, num, shp, "2026-11-12", pro, lines, total, "College Park, GA", "Dallas, TX", sd); c.showPage(); c.save()
print("ok")
